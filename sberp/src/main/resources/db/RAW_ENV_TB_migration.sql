       t.TEMP, t.TEMP_PLUS, t.HMDT, t.HMDT_PLUS, t.BRMT, t.BRMT_PLUS,
       r.TEST_BY, t.SIGN, t.SIGN_URL, 1, IFNULL(NULLIF(t.INS_MEM_ID, ''), 'MIG'), NOW()
  FROM (SELECT s.RAW_SEQ,
               MAKEDATE(s.MSRMN_YEAR, 1) + INTERVAL (s.MSRMN_MON - 1) MONTH + INTERVAL (s.MSRMN_DAY - 1) DAY
           + INTERVAL LEAST(GREATEST(IFNULL(s.MSRMN_HOUR, 0), 0), 23) HOUR
           + INTERVAL LEAST(GREATEST(IFNULL(s.MSRMN_MIN, 0), 0), 59) MINUTE AS DT,
               s.TEMP AS TEMP, s.TEMP_PLUS AS TEMP_PLUS, s.HMDT AS HMDT, s.HMDT_PLUS AS HMDT_PLUS,
               NULL AS BRMT, NULL AS BRMT_PLUS,
               s.SIGN AS SIGN, s.SIGN_URL AS SIGN_URL, s.INS_MEM_ID
          FROM METHOD_CE_TB s
         WHERE s.MSRMN_YEAR BETWEEN 2000 AND 2099 AND s.MSRMN_MON BETWEEN 1 AND 12
           AND s.MSRMN_DAY BETWEEN 1 AND DAY(LAST_DAY(MAKEDATE(s.MSRMN_YEAR, 1) + INTERVAL (s.MSRMN_MON - 1) MONTH))
       ) t
       LEFT JOIN RAW_TB r ON r.RAW_SEQ = t.RAW_SEQ
 WHERE NOT EXISTS (SELECT 1 FROM RAW_ENV_TB e WHERE e.RAW_SEQ = t.RAW_SEQ AND e.MET_KEY = 'CE');

