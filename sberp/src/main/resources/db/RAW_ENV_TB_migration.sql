       (RAW_SEQ, MET_KEY, ROW_NO, TEST_S_DT, TEST_E_DT,
        TEMP, TEMP_PLUS, HMDT, HMDT_PLUS, BRMT, BRMT_PLUS,
        MEM_NAME, SIGN, SIGN_URL, MIG_YN, INS_MEM_ID, INS_DT)
