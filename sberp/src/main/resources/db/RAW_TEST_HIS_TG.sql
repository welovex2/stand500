-- =====================================================================
-- 로데이터 시험기간·시험방법, 시험 성적서발급일 변경 이력 (변경 전/후) — 운영 반영용
-- 대상 DB : MariaDB 10.1 (erp)
-- 대상    : RAW_HIS_TG(교체), RAW_MET_HIS_UDT_TG(신규), TEST_HIS_TG(신규)
--           + 프로젝트완료 후 수정 기록 : RAW_DONE_EDIT_TB·RAW_DONE_EDIT_LOG(신규), METHOD_*_DONE_*_TG·FILE_RAW_DONE_INS_TG(신규)
-- 프로그램 수정 없음 — 트리거만 반영한다.
--
-- 기록 위치 : 모두 RAW_HIS_TB
--   TB=''           : 기존 저장 시점 행 (기존 동작 그대로)
--   TB='RAW_TB'     : COL = TEST_S_DT / TEST_E_DT
--   TB='RAW_MET_TB' : COL = CHECK_YN:{MET_SEQ} {시험방법명} / TYPE:{MET_SEQ} {시험방법명}
--                     예) CHECK_YN:6 ESD
--   TB='TEST_TB'    : COL = REPORT_DT:{TEST_SEQ} / TEST_REPORT_DT:{TEST_SEQ}
--                     RAW_ID 는 그 시험의 로데이터 RAW_SEQ (재발행 시험은 원본 시험의 로데이터, 앱 selectRawSeqByTestSeq 와 동일).
--                     재발행 시험은 원본과 RAW_ID 를 공유하므로 COL 에 TEST_SEQ 를 붙여 구분한다.
--                     로데이터가 아직 없는 시험은 RAW_ID 가 NULL 로 남는다.
--
-- 변경자 (MEM_ID)
--   RAW_TB     : NEW.UDT_MEM_ID
--   RAW_MET_TB : 수정자 컬럼이 없어 RAW_TB.UDT_MEM_ID (로데이터 저장 시 RAW_TB 가 먼저 갱신됨)
--   TEST_TB    : 앱이 UDT_DT 를 갱신한 수정(/tst/insertReportDt.do)이면 NEW.UDT_MEM_ID,
--                갱신하지 않은 수정(로데이터 기본정보 저장 → updateReport)이면 RAW_TB.UDT_MEM_ID
--
-- 알려진 한계 (프로그램 수정 없이 반영하므로)
--   1) 기존 로데이터 이력 화면(hisList)은 RAW_HIS_TB 를 TB 구분 없이 조회한다.
--      반영 후에는 TB<>'' 인 변경 이력 행도 화면에 저장 이력처럼 함께 나온다.
--   2) 측정일 저장으로 시험기간이 재계산(updateTestDtRange)될 때는 앱이 UDT_MEM_ID 를 갱신하지 않아
--      변경자가 직전 로데이터 기본정보 저장자로 기록된다.
--   3) RAW_TB·RAW_MET_TB 최초 등록(INSERT) 시 값은 기록하지 않는다. 이후 수정부터 변경 전/후가 남는다.
--      수정이라도 변경 전 값이 없는 최초 입력(시험시작·완료일 NULL → 값, 시험규격 빈 값 → 값,
--      체크 NULL → 값)은 기록하지 않는다. 성적서 발급일(TEST_TB)은 최초 발급도 기록한다.
--
-- 시험방법명 출처 : 로데이터 수정 화면 메뉴(CE·RE 탭은 도움말의 세부 항목)와 같은 이름
--   MET_SEQ 대응은 RepController.java 성적서 출력 switch(met.getMetSeq()) 기준
--   메뉴에 없는 11·13·14·15 는 PicType·RepController 의 이름(M-Field, Click, DP, RE 9kHz~30MHz)
--
-- 프로젝트완료 후 수정 기록 (RAW_DONE_EDIT_TB)
--   로데이터 저장 1회 = 1행. 저장 시점에 그 로데이터의 시험(RAW_TB.TEST_SEQ)이 프로젝트완료(18)일 때만 남긴다.
--   TB  : 저장된 테이블 (RAW_TB=기본정보, METHOD_CE_TB 등=시험방법 탭, METHOD_IMG_TB=사진, FILE_RAW_TB=첨부 로데이터)
--   ACT : INSERT(그 탭 첫 저장) / UPDATE(재저장)
--   DONE_DT : 그 시험의 프로젝트완료 처리 시각(TEST_TB.TEST_STATE_DT)
--   무엇이 바뀌었는지(값)는 남기지 않는다. 같은 시각의 RAW_HIS_TB(TB<>'') 행으로 일부 항목의 변경 전/후를 볼 수 있다.
--   기록 실패(예외)는 무시한다 — 기록 때문에 로데이터 저장이 실패하지 않게 하기 위함.
--   한계) 첨부 로데이터 삭제(FILE_DETAIL_TB 상태 변경)와 탭 하위 표(*_SUB_TB)만 바뀌는 경우는 따로 잡지 않는다.
--         하위 표는 항상 그 탭 본 테이블 저장과 함께 일어나므로 본 테이블 행으로 남는다.
-- =====================================================================


-- ---------------------------------------------------------------------
-- 0. 실행 전 확인
--    MariaDB 10.1 은 테이블당 같은 시점·이벤트 트리거를 1개만 허용한다.
--    아래 결과가 RAW_HIS_TG(RAW_TB / AFTER / UPDATE) 1건이어야 한다. 그 외 행이 있으면 반영 중단 후 확인.
-- ---------------------------------------------------------------------
SELECT TRIGGER_NAME, EVENT_OBJECT_TABLE, ACTION_TIMING, EVENT_MANIPULATION
  FROM information_schema.TRIGGERS
 WHERE EVENT_OBJECT_SCHEMA = DATABASE()
   AND EVENT_OBJECT_TABLE IN ('RAW_TB', 'RAW_MET_TB', 'TEST_TB',
                              'METHOD_CE_TB', 'METHOD_RE_TB', 'METHOD_ESD_TB', 'METHOD_RS_TB', 'METHOD_EFT_TB',
                              'METHOD_SURGE_TB', 'METHOD_CS_TB', 'METHOD_MF_TB', 'METHOD_VDIP_TB', 'METHOD_CK_TB',
                              'METHOD_DP_TB', 'METHOD_TEL_TB', 'METHOD_IMG_TB', 'FILE_RAW_TB');

-- 완료 후 수정 기록용 대상 테이블 14개가 모두 있어야 한다 (결과 14)
SELECT COUNT(*)
  FROM information_schema.TABLES
 WHERE TABLE_SCHEMA = DATABASE()
   AND TABLE_NAME IN ('METHOD_CE_TB', 'METHOD_RE_TB', 'METHOD_ESD_TB', 'METHOD_RS_TB', 'METHOD_EFT_TB',
