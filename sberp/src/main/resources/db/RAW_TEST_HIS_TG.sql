-- ---------------------------------------------------------------------
-- 1-0. 프로젝트완료 후 수정 기록 테이블·프로시저 (트리거보다 먼저 만든다)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS RAW_DONE_EDIT_TB (
    DONE_EDIT_SEQ INT NOT NULL AUTO_INCREMENT,
    RAW_SEQ       INT          NULL     COMMENT '로데이터 (첨부 로데이터 FILE_RAW_TB 는 NULL)',
    TEST_SEQ      INT          NOT NULL COMMENT '프로젝트완료 상태였던 시험',
    TB            VARCHAR(45)  NOT NULL COMMENT '저장된 테이블',
    ACT           VARCHAR(10)  NOT NULL COMMENT 'INSERT / UPDATE',
    MEM_ID        VARCHAR(20)  NULL     COMMENT '저장한 사람',
    DONE_DT       DATETIME     NULL     COMMENT '프로젝트완료 처리 시각 (TEST_TB.TEST_STATE_DT)',
    INS_DT        DATETIME     NOT NULL COMMENT '저장 시각',
    PRIMARY KEY (DONE_EDIT_SEQ),
    KEY IDX_RAW_DONE_EDIT_TEST (TEST_SEQ),
    KEY IDX_RAW_DONE_EDIT_INS_DT (INS_DT)
) ENGINE=InnoDB DEFAULT CHARSET=utf8 COMMENT='프로젝트완료 후 로데이터 수정 기록';

DROP PROCEDURE IF EXISTS RAW_DONE_EDIT_LOG;

DELIMITER ;;

-- 저장된 로데이터의 시험이 프로젝트완료(18)면 1행 남긴다. p_test_seq 가 NULL 이면 RAW_TB 에서 찾는다.
CREATE PROCEDURE RAW_DONE_EDIT_LOG(IN p_raw_seq INT, IN p_test_seq INT, IN p_tb VARCHAR(45),
                                   IN p_act VARCHAR(10), IN p_mem VARCHAR(20))
BEGIN
    DECLARE v_test_seq INT;
    -- 기록 실패로 로데이터 저장이 막히지 않게 한다
    DECLARE CONTINUE HANDLER FOR SQLEXCEPTION BEGIN END;

    SET v_test_seq = IFNULL(p_test_seq, (SELECT TEST_SEQ FROM RAW_TB WHERE RAW_SEQ = p_raw_seq LIMIT 1));

    INSERT INTO RAW_DONE_EDIT_TB (RAW_SEQ, TEST_SEQ, TB, ACT, MEM_ID, DONE_DT, INS_DT)
    SELECT p_raw_seq, TEST_SEQ, p_tb, p_act, p_mem, TEST_STATE_DT, NOW()
      FROM TEST_TB
     WHERE TEST_SEQ = v_test_seq
       AND TEST_STATE_CODE = '18';
END;;

DELIMITER ;


