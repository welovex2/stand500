-- 시료 구역 이동 이력
-- STR_ZONE_TB.sql 을 먼저 적용한 뒤 실행한다.

DROP TABLE IF EXISTS `IM_SUB_LOC_TB`;
DROP TABLE IF EXISTS `STORE_TB`;

CREATE TABLE `IM_SUB_LOC_TB` (
  `IM_SUB_LOC_SEQ` int NOT NULL AUTO_INCREMENT,
  `IM_ID` varchar(20) NOT NULL,
  `IM_SUB_SEQ` int NOT NULL,
  `ZONE_SEQ` int NOT NULL COMMENT 'ZONE_TB.ZONE_SEQ',
  `MEMO` varchar(500) DEFAULT NULL,
  `INS_MEM_ID` varchar(20) DEFAULT NULL,
  `INS_DT` datetime DEFAULT CURRENT_TIMESTAMP,
  `UDT_MEM_ID` varchar(20) DEFAULT NULL,
  `UDT_DT` datetime DEFAULT CURRENT_TIMESTAMP,
  `STATE` varchar(1) NOT NULL DEFAULT 'I',
  PRIMARY KEY (`IM_SUB_LOC_SEQ`),
  KEY `IDX_IM_SUB_LOC_ITEM` (`IM_ID`,`IM_SUB_SEQ`,`IM_SUB_LOC_SEQ`),
  KEY `IDX_IM_SUB_LOC_ZONE` (`ZONE_SEQ`,`IM_SUB_LOC_SEQ`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8 COMMENT='시료 구역 이동 이력';

CREATE TABLE IF NOT EXISTS `IM_SUB_OCCUPY_TB` (
  `OCCUPY_SEQ` int NOT NULL AUTO_INCREMENT,
  `IM_ID` varchar(20) NOT NULL,
  `IM_SUB_SEQ` int NOT NULL,
  `TEST_TYPE_CODE` varchar(10) NOT NULL COMMENT 'TEST_TB.TEST_TYPE_CODE',
  `OCCUPY_STATE` varchar(10) NOT NULL COMMENT 'IN_USE/RELEASED',
  `TEST_SEQ` int DEFAULT NULL,
  `MEMO` varchar(500) DEFAULT NULL,
  `INS_MEM_ID` varchar(20) DEFAULT NULL,
  `INS_DT` datetime DEFAULT CURRENT_TIMESTAMP,
  `UDT_MEM_ID` varchar(20) DEFAULT NULL,
  `UDT_DT` datetime DEFAULT CURRENT_TIMESTAMP,
  `STATE` varchar(1) NOT NULL DEFAULT 'I',
  PRIMARY KEY (`OCCUPY_SEQ`),
  KEY `IDX_IM_SUB_OCCUPY_ITEM` (`IM_ID`,`IM_SUB_SEQ`,`OCCUPY_SEQ`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8 COMMENT='시료 시험부 점유';

-- 이미 있으면 해당 구문만 건너뛴다.
ALTER TABLE `IM_SUB_TB`
  ADD COLUMN `PROC_STATE` varchar(10) DEFAULT NULL COMMENT '프로세스 상태',
  ADD COLUMN `OCCUPY_TEST_TYPE` varchar(10) DEFAULT NULL,
  ADD COLUMN `OCCUPY_MEM_ID` varchar(20) DEFAULT NULL;

ALTER TABLE `IM_SUB_TB`
  DROP COLUMN `CURRENT_STORE_SEQ`;
